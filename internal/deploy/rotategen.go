// Strategies that apply a new generated secret value (x-yoho.rotate).
const (
	RotatePostgres = "postgres"
	RotateMySQL    = "mysql"
	RotateCommand  = "command"
	RotateNone     = "none"
)

// GeneratedRotation is the plan to rotate one generated secret. It holds
// names only, never values.
type GeneratedRotation struct {
	Key       string
	Kind      string   // generator, as in x-yoho.generate
	Service   string   // Service that generates Key; its container applies it
	Strategy  string   // RotatePostgres, RotateMySQL, RotateCommand or RotateNone
	Detected  bool     // Strategy was detected, not set in x-yoho.rotate
	User      string   // database role (postgres, mysql)
	MariaDB   bool     // mysql strategy against a MariaDB server
	Command   []string // RotateCommand
	Consumers []string // Services that receive Key (sorted)
}

// RotationsLog is the per-Destination audit log of generated-secret
// rotations (JSON lines, fingerprints only).
func RotationsLog(app, dest string) string {
	return path.Join(release.AppDir(app, dest), "rotations.jsonl")
}

// RotationRecord is one line of RotationsLog. Fingerprint is the keyed
// digest (hmac.key) of the new value, as in Release secret audits.
type RotationRecord struct {
	Time        time.Time `json:"time"`
	Performer   string    `json:"performer"`
	Key         string    `json:"key"`
	Service     string    `json:"service"`
	Strategy    string    `json:"strategy"`
	Consumers   []string  `json:"consumers,omitempty"`
	Fingerprint string    `json:"fingerprint"`
}

var (
	rotateUserRe = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9_.-]{0,62}$`)
	mysqlRootKey = map[string]bool{"MYSQL_ROOT_PASSWORD": true, "MARIADB_ROOT_PASSWORD": true}
	mysqlUserKey = map[string]bool{"MYSQL_PASSWORD": true, "MARIADB_PASSWORD": true}
)

// imageBase is the last path element of an image reference, lowercased,
// without tag or digest ("ghcr.io/x/postgres:17" -> "postgres").
func imageBase(image string) string {
	ref := strings.ToLower(image)
	if i := strings.Index(ref, "@"); i >= 0 {
		ref = ref[:i]
	}
	if i := strings.LastIndex(ref, ":"); i > strings.LastIndex(ref, "/") {
		ref = ref[:i]
	}
	return path.Base(ref)
}

// imageFamily returns "postgres", "mysql" or "" for an image reference.
func imageFamily(image string) string {
	name := imageBase(image)
	switch {
	case strings.Contains(name, "postgres"), strings.HasPrefix(name, "postgis"), strings.HasPrefix(name, "pgvector"), strings.HasPrefix(name, "timescaledb"):
		return RotatePostgres
	case strings.HasPrefix(name, "mysql"), strings.HasPrefix(name, "mariadb"), strings.HasPrefix(name, "percona"):
		return RotateMySQL
	}
	return ""
}

// PlanGeneratedRotation decides how key is rotated: which Service applies
// it, with which strategy and database user, and which Services restart.
func PlanGeneratedRotation(d *plan.Deploy, key string) (*GeneratedRotation, error) {
	kinds, err := generatedDecls(d)
	if err != nil {
		return nil, err
	}
	kind, ok := kinds[key]
	if !ok {
		return nil, fmt.Errorf("%s is not a generated secret (no Service declares it in x-yoho.generate)", key)
	}
	var owners, explicit, databases []string
	for _, svc := range sortedKeys(d.Ext) {
		ext := d.Ext[svc]
		if _, ok := ext.Generate[key]; !ok {
			continue
		}
		owners = append(owners, svc)
		if _, ok := ext.Rotate[key]; ok {
			explicit = append(explicit, svc)
		}
		if sc, ok := d.Project.Services[svc]; ok && imageFamily(sc.Image) != "" {
			databases = append(databases, svc)
		}
	}
	var owner string
	switch {
	case len(explicit) == 1:
		owner = explicit[0]
	case len(explicit) > 1:
		return nil, fmt.Errorf("%s has x-yoho.rotate on %s; keep it on one Service", key, strings.Join(explicit, " and "))
	case len(owners) == 1:
		owner = owners[0]
	case len(databases) == 1:
		owner = databases[0]
	default:
		return nil, fmt.Errorf("%s is generated by %s; set x-yoho.rotate.%s on the Service that stores it", key, strings.Join(owners, " and "), key)
	}
	sc, ok := d.Project.Services[owner]
	if !ok {
		return nil, fmt.Errorf("service %s is not in the compose project", owner)
	}
	ext := d.Ext[owner]
	g := &GeneratedRotation{Key: key, Kind: kind, Service: owner}
	if spec, ok := ext.Rotate[key]; ok {
		g.Strategy, g.User, g.Command = spec.Strategy, spec.User, spec.Command
	} else {
		g.Detected = true
		switch {
		case key == "POSTGRES_PASSWORD":
			g.Strategy = RotatePostgres
		case mysqlRootKey[key] || mysqlUserKey[key]:
			g.Strategy = RotateMySQL
		case imageFamily(sc.Image) != "" || ext.Stateful:
			return nil, fmt.Errorf("cannot tell how Service %s stores %s; set x-yoho.rotate.%s.strategy (postgres, mysql, command or none)", owner, key, key)
		default:
			g.Strategy = RotateNone
		}
	}
	env := func(name string) string {
		if v, ok := sc.Environment[name]; ok && v != nil {
			return *v
		}
		return ""
	}
	switch g.Strategy {
	case RotatePostgres:
		if g.User == "" {
			g.User = env("POSTGRES_USER")
		}
		if g.User == "" {
			g.User = "postgres"
		}
	case RotateMySQL:
		g.MariaDB = strings.HasPrefix(imageBase(sc.Image), "mariadb") || strings.HasPrefix(key, "MARIADB_")
		if g.User == "" {
			switch {
			case mysqlRootKey[key]:
				g.User = "root"
			case env("MYSQL_USER") != "":
				g.User = env("MYSQL_USER")
			case env("MARIADB_USER") != "":
				g.User = env("MARIADB_USER")
			default:
				return nil, fmt.Errorf("service %s: no MYSQL_USER for %s; set x-yoho.rotate.%s.user", owner, key, key)
			}
		}
	case RotateCommand:
		if len(g.Command) == 0 {
			return nil, fmt.Errorf("x-yoho.rotate.%s: strategy command needs a command", key)
		}
	case RotateNone:
	default:
		return nil, fmt.Errorf("x-yoho.rotate.%s: unknown strategy %q", key, g.Strategy)
	}
	if g.User != "" && !rotateUserRe.MatchString(g.User) {
		return nil, fmt.Errorf("service %s: database user %q for %s must match %s", owner, g.User, key, rotateUserRe)
	}
	for _, svc := range sortedKeys(d.Ext) {
		ext := d.Ext[svc]
		uses := false
		if _, ok := ext.Generate[key]; ok {
			uses = true
		}
		for _, ref := range ext.Secrets {
			if ref.Key == key {
				uses = true
			}
		}
		if uses {
			g.Consumers = append(g.Consumers, svc)
		}
	}
	return g, nil
}

// RotateGeneratedSecret gives g.Key a new value from the same generator:
// it writes generated/<Key>.next, applies it to the database in g.Service's
// running container, then renames it over generated/<Key>. Consumers are
// not restarted here (run the secrets rotate rollout next). The caller
// holds the Destination lock.
//
// If the database step fails, generated/<Key> keeps the old value and the
// pending one stays, so a re-run applies the same value again (the strategy
// authenticates with either value). Once the database took the new value,
// a failed login check is passed to warnf and the swap still happens, so
// the database and generated/<Key> agree. If the swap itself fails the
// error is a *PendingSwapError: the database already uses the value in
// generated/<Key>.next. After the swap, generated/<Key>.swapped holds the
// new value's fingerprint until the rollout finishes (RotationSwapped,
// ClearRotationSwapped). Values travel over stdin or the env file of
// remote.Cmd, never in a script or argv, and errors are scrubbed.
func RotateGeneratedSecret(ctx context.Context, h remote.Host, app, dest, performer string, g *GeneratedRotation, logf, warnf func(string, ...any)) (err error) {
	if logf == nil {
		logf = func(string, ...any) {}
	}
	if warnf == nil {
		warnf = logf
	}
	dir := release.AppDir(app, dest)
	p := path.Join(dir, "generated", g.Key)
	old, err := h.ReadFile(ctx, p, false)
	if errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("generated secret %s is not on the Server yet; run yoho deploy first", g.Key)
	}
	if err != nil {
		return fmt.Errorf("read generated secret %s: %w", g.Key, err)
	}
	if len(old) == 0 {
		return fmt.Errorf("generated secret %s is empty on the Server", g.Key)
	}
	fresh, err := secrets.Generate(g.Kind)
	if err != nil {
		return fmt.Errorf("generated secret %s: %w", g.Key, err)
	}
	next, err := ensureFileOnce(ctx, h, p+".next", []byte(fresh))
	if err != nil {
		return err
	}
	if len(next) == 0 || bytes.Equal(next, old) {
		_ = h.Run(ctx, remote.Cmd{Script: "rm -f " + remote.Quote(p+".next")})
		return fmt.Errorf("pending value for %s was empty or unchanged and was removed; run the rotation again", g.Key)
	}
	if string(next) != fresh {
		logf("resuming the pending rotation of %s", g.Key)
	}
	if g.Strategy != RotateNone {
		cid, err := runningContainer(ctx, h, release.ProjectName(app, dest), g.Service)
		if err != nil {
			return err
		}
		logf("applying the new %s through %s (%s)", g.Key, g.Service, g.Strategy)
		warn, err := applyRotation(ctx, h, cid, g, old, next)
		if err != nil {
			return err
		}
		if warn != "" {
			warnf("%s", warn)
		}
	}
	key, err := ensureHMACKey(ctx, h, dir)
	if err != nil {
		return &PendingSwapError{Key: g.Key, Applied: g.Strategy != RotateNone, Err: err}
	}
	fp := secrets.Fingerprint(key, string(next))
	if err := h.Run(ctx, remote.Cmd{Script: swapScript(p), Stdin: strings.NewReader(fp + "\n")}); err != nil {
		return &PendingSwapError{Key: g.Key, Applied: g.Strategy != RotateNone, Err: err}
	}
	rec, err := json.Marshal(RotationRecord{
		Time: now().UTC(), Performer: performer, Key: g.Key, Service: g.Service, Strategy: g.Strategy,
		Consumers: g.Consumers, Fingerprint: fp,
	})
	if err != nil {
		return err
	}
	if err := h.Run(ctx, remote.Cmd{Script: "set -eu\numask 077\ncat >> " + remote.Quote(RotationsLog(app, dest)), Stdin: bytes.NewReader(append(rec, '\n'))}); err != nil {
		logf("could not append to %s: %v", RotationsLog(app, dest), err)
	}
	return nil
}

// PendingSwapError means the new value was applied to the database (when
// Applied) but could not replace generated/<Key>: the database uses the
// value in generated/<Key>.next. A re-run of the rotation finishes it.
type PendingSwapError struct {
	Key     string
	Applied bool
	Err     error
}

func (e *PendingSwapError) Error() string {
	return fmt.Sprintf("swap generated secret %s: %v", e.Key, e.Err)
}

func (e *PendingSwapError) Unwrap() error { return e.Err }

// swapScript renames generated/<Key>.next over generated/<Key>. It first
// writes the swap marker (the new value's fingerprint, from stdin), so a
// run interrupted after the rename knows the rollout is still pending
// (RotationSwapped). A marker left without the rename is ignored: .next
// still exists, and the database step resumes.
func swapScript(p string) string {
	n := remote.Quote(p + ".next")
	m := remote.Quote(swappedMarker(p))
	t := remote.Quote(swappedMarker(p) + ".tmp")
	return "set -eu\numask 077\ntest -s " + n + "\ncat > " + t + "\nmv -f " + t + " " + m + "\nchmod 600 " + n + "\nmv -f " + n + " " + remote.Quote(p)
}

// runningContainer returns the ID of a running container of svc.
func runningContainer(ctx context.Context, h remote.Host, project, svc string) (string, error) {
	out, err := h.Output(ctx, remote.Cmd{Script: "set -eu\ndocker ps -q --no-trunc --filter " + remote.Quote("label=com.docker.compose.project="+project) +
		" --filter " + remote.Quote("label=com.docker.compose.service="+svc) +
		" --filter " + remote.Quote("label=com.docker.compose.oneoff=False") + " --filter status=running"})
	if err != nil {
		return "", fmt.Errorf("find the container of %s: %w", svc, err)
	}
	ids := lines(out)
	if len(ids) == 0 {
		return "", fmt.Errorf("service %s has no running container to apply the new value; run yoho deploy, then rotate again", svc)
	}
	return ids[0], nil
}

// applyRotation runs the strategy. It first authenticates with the old
// value; if the database already took the new one (an earlier run stopped
// after the database step), it retries with the new value. Remote stderr is
// captured and scrubbed of both values before it becomes an error. An error
// means the database step failed; once it succeeded, a failed login check
// with the new value is returned as a warning instead, because the database
// already uses the new value.
func applyRotation(ctx context.Context, h remote.Host, cid string, g *GeneratedRotation, old, next []byte) (warning string, err error) {
	run := func(c remote.Cmd) error { return runScrubbed(ctx, h, c, string(old), string(next)) }
	switch g.Strategy {
	case RotatePostgres:
		verifier, err := scramSHA256Verifier(string(next))
		if err != nil {
			return "", fmt.Errorf("ALTER ROLE %s: %w", g.User, err)
		}
		sql := postgresSQL(g.User, verifier)
		if err := withEither(old, next, func(auth []byte) error {
			return run(remote.Cmd{Script: postgresAlterScript(cid, g.User), Stdin: strings.NewReader(sql), Env: map[string]string{"PGPASSWORD": string(auth)}})
		}); err != nil {
			return "", fmt.Errorf("ALTER ROLE %s: %w", g.User, err)
		}
		if err := run(remote.Cmd{Script: postgresVerifyScript(cid, g.User), Env: map[string]string{"PGPASSWORD": string(next)}}); err != nil {
			return fmt.Sprintf("the database took the new password for %s; could not confirm a network login: %v", g.User, err), nil
		}
		return "", nil
	case RotateMySQL:
		if err := withEither(old, next, func(auth []byte) error {
			p, err := probeMySQL(ctx, h, cid, g, string(auth), string(old), string(next))
			if err != nil {
				return err
			}
			sql, err := mysqlRotationSQL(g.User, string(next), p)
			if err != nil {
				return err
			}
			in, err := mysqlStdin(g.User, string(auth), sql)
			if err != nil {
				return err
			}
			return run(remote.Cmd{Script: mysqlScript(cid), Stdin: bytes.NewReader(in)})
		}); err != nil {
			return "", fmt.Errorf("change the password of %s: %w", g.User, err)
		}
		in, err := mysqlStdin(g.User, string(next), "SELECT 1;\n")
		if err == nil {
			err = run(remote.Cmd{Script: mysqlScript(cid), Stdin: bytes.NewReader(in)})
		}
		if err != nil {
			return fmt.Sprintf("the database took the new password for %s; could not confirm a login with it: %v", g.User, err), nil
		}
		return "", nil
	case RotateCommand:
		if err := run(remote.Cmd{Script: commandScript(cid, g.Command), Stdin: strings.NewReader(commandStdin(string(old), string(next)))}); err != nil {
			return "", fmt.Errorf("x-yoho.rotate.%s.command: %w", g.Key, err)
		}
		return "", nil
	}
	return "", fmt.Errorf("unknown strategy %q", g.Strategy)
}

// withEither calls f with the old value, then with the new one. When both
// fail it reports the first error: the old value is the normal case.
func withEither(old, next []byte, f func([]byte) error) error {
	err := f(old)
	if err == nil {
		return nil
	}
	if f(next) == nil {
		return nil
	}
	return err
}

// runScrubbed runs c with stderr captured; the error text never contains
// vals (a database client may echo the failed statement).
func runScrubbed(ctx context.Context, h remote.Host, c remote.Cmd, vals ...string) error {
	var stderr bytes.Buffer
	c.Stderr = &stderr
	return scrubError(h, h.Run(ctx, c), &stderr, vals)
}

// outputScrubbed is runScrubbed returning stdout.
func outputScrubbed(ctx context.Context, h remote.Host, c remote.Cmd, vals ...string) (string, error) {
	var stderr bytes.Buffer
	c.Stderr = &stderr
	out, err := h.Output(ctx, c)
	return out, scrubError(h, err, &stderr, vals)
}

func scrubError(h remote.Host, err error, stderr *bytes.Buffer, vals []string) error {
	if err == nil {
		return nil
	}
	msg := strings.TrimSpace(stderr.String())
	for _, v := range vals {
		if v != "" {
			msg = strings.ReplaceAll(msg, v, "[REDACTED]")
		}
	}
	if len(msg) > 2000 {
		msg = msg[len(msg)-2000:]
	}
	code := "error"
	var ee *remote.ExitError
	if errors.As(err, &ee) {
		code = fmt.Sprintf("exit %d", ee.Code)
	}
	if msg == "" {
		return fmt.Errorf("remote command failed on %s (%s)", h.Name(), code)
	}
	return fmt.Errorf("remote command failed on %s (%s): %s", h.Name(), code, msg)
}

// sqlLiteral quotes s as a standard SQL string literal.
func sqlLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// pgIdent quotes s as a Postgres identifier.
func pgIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

// postgresSQL is fed to psql on stdin. verifier is a SCRAM-SHA-256
// verifier (scramSHA256Verifier), never the password: Postgres stores a
// verifier as given, so the plaintext never reaches the server, whose
// statement log (log_statement=ddl or all) would otherwise record it.
// Statement logging is also turned off for the session (superuser only;
// ignored otherwise) so not even the verifier is logged when allowed.
func postgresSQL(user, verifier string) string {
	return "\\set VERBOSITY terse\n\\set ON_ERROR_STOP 0\nSET log_statement = 'none';\nSET log_min_error_statement = 'panic';\nSET log_min_duration_statement = -1;\n\\set ON_ERROR_STOP 1\n" +
		"ALTER ROLE " + pgIdent(user) + " WITH PASSWORD " + sqlLiteral(verifier) + ";\n"
}

const scramIterations = 4096 // the Postgres default (scram_iterations)

// scramSHA256Verifier computes the Postgres SCRAM-SHA-256 verifier of
// password (RFC 5802 / RFC 7677) with a random 16-byte salt:
// SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>, base64.
func scramSHA256Verifier(password string) (string, error) {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	return scramVerifierWithSalt(password, salt, scramIterations)
}

func scramVerifierWithSalt(password string, salt []byte, iter int) (string, error) {
	// SASLprep is the identity on printable ASCII, which is all generated
	// values use (letters, digits, hex, base64); anything else is refused
	// rather than hashed differently than the server would.
	if !printableASCII(password) {
		return "", errors.New("generated value is not printable ASCII; cannot compute its SCRAM verifier")
	}
	salted, err := pbkdf2.Key(sha256.New, password, salt, iter, sha256.Size)
	if err != nil {
		return "", err
	}
	mac := func(key []byte, msg string) []byte {
		m := hmac.New(sha256.New, key)
		m.Write([]byte(msg))
		return m.Sum(nil)
	}
	stored := sha256.Sum256(mac(salted, "Client Key"))
	b64 := base64.StdEncoding.EncodeToString
	return fmt.Sprintf("SCRAM-SHA-256$%d:%s$%s:%s", iter, b64(salt), b64(stored[:]), b64(mac(salted, "Server Key"))), nil
}

func printableASCII(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < 0x20 || s[i] > 0x7e {
			return false
		}
	}
	return true
}

// postgresAlterScript reads SQL from stdin over the container's local
// socket; PGPASSWORD comes from the env file, passed by name only.
func postgresAlterScript(cid, user string) string {
	return "set -eu\ndocker exec -i -e PGPASSWORD " + remote.Quote(cid) + " psql -X -q -v ON_ERROR_STOP=1 -U " + remote.Quote(user) + " -d postgres -f - >/dev/null"
}

// postgresVerifyScript logs in over TCP on the container's network
// address, read with docker inspect on the Server (nothing needed in the
// image): the official images trust the local socket and loopback, so only
// a non-loopback login checks the password. Without a network address the
// check is skipped and says so, rather than passing over loopback.
func postgresVerifyScript(cid, user string) string {
	return "set -eu\n" +
		"set -- $(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}} {{end}}' " + remote.Quote(cid) + ")\n" +
		"if [ -z \"${1:-}\" ]; then echo 'no container network address: skipped checking the new password over the network' >&2; exit 0; fi\n" +
		"docker exec -e PGPASSWORD " + remote.Quote(cid) + " psql -X -q -w -h \"$1\" -U " + remote.Quote(user) + " -d postgres -c 'SELECT 1' >/dev/null\n"
}

// mysqlString quotes s as a MySQL string literal (backslash escapes on).
func mysqlString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `''`).Replace(s) + "'"
}

// mysqlSQL changes the password of user. root has two accounts in the
// official images (localhost and %) and may alter both. Other users change
// their own: ALTER USER CURRENT_USER() on MySQL; MariaDB requires CREATE
// USER for that, so it uses SET PASSWORD.
func mysqlSQL(user, password string, mariadb bool) string {
	pw := mysqlString(password)
	switch {
	case user == "root":
		return "ALTER USER IF EXISTS 'root'@'localhost' IDENTIFIED BY " + pw + ", 'root'@'%' IDENTIFIED BY " + pw + ";\n"
	case mariadb:
		return "SET PASSWORD = PASSWORD(" + pw + ");\n"
	}
	return "ALTER USER CURRENT_USER() IDENTIFIED BY " + pw + ";\n"
}

// mysqlProbe is what a rotation learns about a MySQL or MariaDB server and
// account before it sends a new password, so the plaintext never lands in
// the general log (which `yoho app logs` may show).
type mysqlProbe struct {
	MariaDB    bool
	GeneralLog bool // general_log is ON
	SlowLog    bool // slow_query_log is ON
	LogRaw     bool // MySQL log_raw is ON: passwords are not rewritten in logs
	LogOff     bool // this account may SET SESSION sql_log_off=1
	Native     bool // MariaDB account authenticates with mysql_native_password
}

const mysqlProbeSQL = "SHOW GLOBAL VARIABLES WHERE Variable_name IN ('version','general_log','slow_query_log','log_raw');\n"

var mariadbOtherPluginRe = regexp.MustCompile(`(?i)\bVIA\s+(ed25519|parsec|pam|gssapi|named_pipe|caching_sha2_password|sha256_password)\b`)

// probeMySQL reads the logging variables, tries sql_log_off, and on MariaDB
// reads the account's authentication plugin, each as user with auth.
// Failure of the first query (authentication) is an error; the others only
// leave their fields false.
func probeMySQL(ctx context.Context, h remote.Host, cid string, g *GeneratedRotation, auth string, vals ...string) (mysqlProbe, error) {
	query := func(sql string) (string, error) {
		in, err := mysqlStdin(g.User, auth, sql)
		if err != nil {
			return "", err
		}
		return outputScrubbed(ctx, h, remote.Cmd{Script: mysqlQueryScript(cid), Stdin: bytes.NewReader(in)}, vals...)
	}
	p := mysqlProbe{MariaDB: g.MariaDB}
	out, err := query(mysqlProbeSQL)
	if err != nil {
		return p, err
	}
	for _, l := range lines(out) {
		name, val, _ := strings.Cut(l, "\t")
		on := strings.EqualFold(strings.TrimSpace(val), "ON") || strings.TrimSpace(val) == "1"
		switch strings.ToLower(strings.TrimSpace(name)) {
		case "version":
			p.MariaDB = strings.Contains(strings.ToLower(val), "mariadb")
		case "general_log":
			p.GeneralLog = on
		case "slow_query_log":
			p.SlowLog = on
		case "log_raw":
			p.LogRaw = on
		}
	}
	if _, err := query("SET SESSION sql_log_off=1;\n"); err == nil {
		p.LogOff = true
	}
	if p.MariaDB {
		if out, err := query("SHOW CREATE USER CURRENT_USER();\n"); err == nil {
			p.Native = (strings.Contains(out, "IDENTIFIED BY PASSWORD '*") || strings.Contains(strings.ToLower(out), "via mysql_native_password")) &&
				!mariadbOtherPluginRe.MatchString(out)
		}
	}
	return p, nil
}

// mysqlNativeHash is the mysql_native_password hash of password:
// '*' + uppercase hex SHA1(SHA1(password)).
func mysqlNativeHash(password string) string {
	a := sha1.Sum([]byte(password))
	b := sha1.Sum(a[:])
	return "*" + strings.ToUpper(hex.EncodeToString(b[:]))
}

// mysqlRotationSQL is the session that changes user's password without
// the plaintext reaching a log. sql_log_off is set first when allowed. A
// MariaDB mysql_native_password account gets a client-computed hash, as
// MariaDB writes statements to its general log verbatim. MySQL rewrites the
// password in ALTER USER in its logs unless log_raw is on. Otherwise, if the
// general (or, on MariaDB, slow) log would record the plaintext, the
// rotation is refused.
func mysqlRotationSQL(user, password string, p mysqlProbe) (string, error) {
	pre := ""
	if p.LogOff {
		pre = "SET SESSION sql_log_off=1;\n"
	}
	if p.MariaDB && p.Native {
		h := sqlLiteral(mysqlNativeHash(password))
		if user == "root" {
			return pre + "ALTER USER IF EXISTS 'root'@'localhost' IDENTIFIED BY PASSWORD " + h + ", 'root'@'%' IDENTIFIED BY PASSWORD " + h + ";\n", nil
		}
		return pre + "SET PASSWORD = " + h + ";\n", nil
	}
	generalLeaks := p.GeneralLog && !p.LogOff
	switch {
	case p.MariaDB && (generalLeaks || p.SlowLog):
		return "", fmt.Errorf("MariaDB would write the new password of %s to its general or slow query log: the account does not use mysql_native_password (so Yoho cannot send a hash) and cannot SET sql_log_off; turn general_log and slow_query_log off, grant it SUPER, or set the password by hand", user)
	case !p.MariaDB && generalLeaks && p.LogRaw:
		return "", fmt.Errorf("MySQL runs with log_raw, so its general log would record the new password of %s, and the account cannot SET sql_log_off; turn log_raw or general_log off, or set the password by hand", user)
	}
	return pre + mysqlSQL(user, password, p.MariaDB), nil
}

const mysqlSQLMarker = "#yoho-sql"

// mysqlStdin is an option file (the credentials), a marker line, then SQL.
// The container script writes the option file to a private temp file.
func mysqlStdin(user, password, sql string) ([]byte, error) {
	if strings.ContainsAny(password, "\"\n\r\x00") || strings.ContainsAny(user, "\"\n\r\x00") {
		return nil, fmt.Errorf("value cannot be written to a mysql option file")
	}
	q := strings.NewReplacer(`\`, `\\`)
	return []byte("[client]\nuser=\"" + q.Replace(user) + "\"\npassword=\"" + q.Replace(password) + "\"\n" + mysqlSQLMarker + "\n" + sql), nil
}

// mysqlScript runs inside the container: copy stdin up to the marker into
// a 0600 option file, then run the client on the rest of stdin.
func mysqlScript(cid string) string { return mysqlClientScript(cid, " >/dev/null") }

// mysqlQueryScript is mysqlScript with the client's tab-separated output on
// stdout (the probe queries; never values).
func mysqlQueryScript(cid string) string { return mysqlClientScript(cid, "") }

func mysqlClientScript(cid, redirect string) string {
	inner := `set -eu
umask 077
f=$(mktemp)
trap 'rm -f "$f"' EXIT
while IFS= read -r l; do
  [ "$l" = "` + mysqlSQLMarker + `" ] && break
  printf '%s\n' "$l" >> "$f"
done
c=mysql
if command -v mariadb >/dev/null 2>&1; then c=mariadb; fi
"$c" --defaults-extra-file="$f" -N -B` + redirect
	return "set -eu\ndocker exec -i " + remote.Quote(cid) + " sh -c " + remote.Quote(inner)
}

func commandStdin(old, next string) string { return old + "\n" + next + "\n" }

func commandScript(cid string, argv []string) string {
	return "set -eu\ndocker exec -i " + remote.Quote(cid) + " " + remote.QuoteArgs(argv...) + " >/dev/null"
}

// ConsumersOf merges the consumers of several rotations (sorted, unique).
func ConsumersOf(gs []*GeneratedRotation) []string {
	var out []string
	for _, g := range gs {
		for _, c := range g.Consumers {
			if !slices.Contains(out, c) {
				out = append(out, c)
			}
		}
	}
	slices.Sort(out)
	return out
}
